// Trusted Types (https://w3c.github.io/trusted-types/dist/spec/). A page that sends
// `Content-Security-Policy: require-trusted-types-for 'script'` only lets DOM sinks such as `innerHTML` and
// `script.text` take values made by a policy: a plain string throws (or, in report-only mode, sends a
// violation report). hal-search creates one policy, named TRUSTED_TYPES_POLICY, and only passes it what it
// generated itself: the markup of the inline SVG (renderSvgParts escapes every dynamic value) and serialized
// JSON-LD (see serializeJsonLd).
// A page that also restricts policy names (`trusted-types ...`) must list it: `trusted-types hal-search`.
//
// Nothing here runs at module load: the SSR imports the main entry in Node.

/** Name of the Trusted Types policy created by hal-search. */
export const TRUSTED_TYPES_POLICY = 'hal-search';

/** The parts of a TrustedTypePolicy used here (lib.dom has no Trusted Types typings). */
interface Policy {
  createHTML(input: string): unknown;
  createScript(input: string): unknown;
}

interface PolicyFactory {
  createPolicy(name: string, rules: { createHTML: (input: string) => string; createScript: (input: string) => string }): Policy;
}

/** One policy per factory (window), created on first use; null when the page refused it. */
const policies = new WeakMap<object, Policy | null>();

/**
 * The hal-search policy of `win`, or undefined when Trusted Types are not supported or the page refuses the
 * policy name (createPolicy throws, e.g. for a second copy of the library when duplicate names are not allowed).
 */
function policyOf(win: unknown): Policy | undefined {
  const factory = (win as { trustedTypes?: PolicyFactory } | null | undefined)?.trustedTypes;
  if (!factory || typeof factory.createPolicy !== 'function') return undefined;
  let policy = policies.get(factory);
  if (policy === undefined) {
    try {
      // Identity rules: the values are generated by hal-search itself, see the comment at the top.
      policy = factory.createPolicy(TRUSTED_TYPES_POLICY, { createHTML: (s) => s, createScript: (s) => s });
    } catch {
      policy = null;
    }
    policies.set(factory, policy);
  }
  return policy ?? undefined;
}

/**
 * `markup` as a TrustedHTML of the hal-search policy, for `innerHTML`; unchanged when Trusted Types are
 * unsupported or the policy was refused (then `innerHTML` throws on a page that enforces them). Only for
 * markup generated by hal-search. Typed as a string: what the DOM typings expect.
 * @internal
 */
export function trustedHtml(win: unknown, markup: string): string {
  const policy = policyOf(win);
  return policy ? (policy.createHTML(markup) as string) : markup;
}

/**
 * `text` as a TrustedScript of the hal-search policy, or undefined when Trusted Types are unsupported or the
 * policy was refused. Only for script text generated by hal-search (JSON-LD). Typed as a string: what the DOM
 * typings expect.
 * @internal
 */
export function trustedScript(win: unknown, text: string): string | undefined {
  const policy = policyOf(win);
  return policy ? (policy.createScript(text) as string) : undefined;
}
